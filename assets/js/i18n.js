  var STORAGE_KEY = "jnhy_lang";
  var current = "zh";

  function apply(lang) {
    var dict = DICT[lang];
    if (!dict) return;

    $$("[data-i18n]").forEach(function (el) {
      var v = dict[el.getAttribute("data-i18n")];
      if (v !== undefined) el.textContent = v;
    });
    $$("[data-i18n-html]").forEach(function (el) {
      var v = dict[el.getAttribute("data-i18n-html")];
      if (v !== undefined) el.innerHTML = v;
    });
    $$("[data-i18n-placeholder]").forEach(function (el) {
      var v = dict[el.getAttribute("data-i18n-placeholder")];
      if (v !== undefined) el.setAttribute("placeholder", v);
    });
    $$("[data-i18n-attr]").forEach(function (el) {
      // 格式：data-i18n-attr="aria-label:key;title:key"
      el.getAttribute("data-i18n-attr")
        .split(";")
        .forEach(function (pair) {
          var bits = pair.split(":");
          if (bits.length !== 2) return;
          var v = dict[bits[1].trim()];
          if (v !== undefined) el.setAttribute(bits[0].trim(), v);
        });
    });

    document.documentElement.setAttribute("lang", lang === "en" ? "en" : "zh-CN");
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}

    $$("[data-lang-toggle]").forEach(function (btn) {
      btn.textContent = dict["lang.toggle"];
      btn.setAttribute("title", dict["lang.toggle.title"]);
      btn.setAttribute("aria-label", dict["lang.toggle.title"]);
    });
  }

  function $$sel(sel) {
    return Array.prototype.slice.call(document.querySelectorAll(sel));
  }
  var $$ = $$sel;

  function init() {
    var saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    if (!saved) {
      var nav = navigator.language || "zh-CN";
      saved = nav.toLowerCase().indexOf("zh") === 0 ? "zh" : "en";
    }
    apply(saved);

    $$("[data-lang-toggle]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        apply(current === "zh" ? "en" : "zh");
      });
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
